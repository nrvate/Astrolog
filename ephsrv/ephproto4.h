// ---- 3.1 primitives ------------------------------------------------------------

enum Outcome : int { kOk = 0, kMalformed = 1, kUnsupported = 11 };

class Writer {
public:
  explicit Writer(std::vector<uint8_t> *out) : out_(out) {}
  void u8(uint8_t v) { out_->push_back(v); }
  void u16(uint16_t v) { for (int i = 0; i < 2; i++) out_->push_back((uint8_t)(v >> (8 * i))); }
  void u32(uint32_t v) { for (int i = 0; i < 4; i++) out_->push_back((uint8_t)(v >> (8 * i))); }
  void u64(uint64_t v) { for (int i = 0; i < 8; i++) out_->push_back((uint8_t)(v >> (8 * i))); }
  void i32(int32_t v) { u32((uint32_t)v); }
  void i64(int64_t v) { u64((uint64_t)v); }
  void f32(float v) { uint32_t u; memcpy(&u, &v, 4); u32(u); }
  void f64(double v) { uint64_t u; memcpy(&u, &v, 8); u64(u); }
  void raw(const void *p, size_t n) {
    const uint8_t *b = (const uint8_t *)p;
    out_->insert(out_->end(), b, b + n);
  }
  // str8: the caller guarantees <= 255 bytes (encoders validate first).
  void str8(const std::string &s) { u8((uint8_t)s.size()); raw(s.data(), s.size()); }
  size_t size() const { return out_->size(); }
  void patchU16(size_t at, uint16_t v) { (*out_)[at] = (uint8_t)v; (*out_)[at + 1] = (uint8_t)(v >> 8); }
  void patchU32(size_t at, uint32_t v) {
    for (int i = 0; i < 4; i++) (*out_)[at + i] = (uint8_t)(v >> (8 * i));
  }
private:
  std::vector<uint8_t> *out_;
};

// Reads latch a failure on truncation and return zeros after it; callers
// check ok() once per structure. Semantic problems are recorded with
// Malformed()/Unsupported() and the parse continues where it can, so the
// first-found malformed rule wins over an unsupported value seen earlier.
class Reader {
public:
  Reader(const uint8_t *p, size_t n) : p_(p), n_(n) {}
  bool ok() const { return !trunc_; }
  size_t left() const { return n_ - pos_; }
  uint8_t u8() { return need(1) ? p_[pos_++] : 0; }
  uint16_t u16() {
    if (!need(2)) return 0;
    uint16_t v = (uint16_t)(p_[pos_] | (p_[pos_ + 1] << 8));
    pos_ += 2;
    return v;
  }
  uint32_t u32() {
    if (!need(4)) return 0;
    uint32_t v = 0;
    for (int i = 3; i >= 0; i--) v = (v << 8) | p_[pos_ + i];
    pos_ += 4;
    return v;
  }
  uint64_t u64() {
    if (!need(8)) return 0;
    uint64_t v = 0;
    for (int i = 7; i >= 0; i--) v = (v << 8) | p_[pos_ + i];
    pos_ += 8;
    return v;
  }
  int32_t i32() { return (int32_t)u32(); }
  int64_t i64() { return (int64_t)u64(); }
  float f32() { uint32_t u = u32(); float f; memcpy(&f, &u, 4); return f; }
  double f64() { uint64_t u = u64(); double d; memcpy(&d, &u, 8); return d; }
  const uint8_t *bytes(size_t n) {
    if (!need(n)) return nullptr;
    const uint8_t *b = p_ + pos_;
    pos_ += n;
    return b;
  }
  std::string str8() {
    uint8_t n = u8();
    const uint8_t *b = bytes(n);
    return b ? std::string((const char *)b, n) : std::string();
  }
private:
  bool need(size_t n) {
    if (trunc_ || n > n_ - pos_) { trunc_ = true; pos_ = n_; return false; }
    return true;
  }
  const uint8_t *p_;
  size_t n_;
  size_t pos_ = 0;
  bool trunc_ = false;
};

// Collects a parse's verdict: malformed wins over unsupported.
class Verdict {
public:
  void Malformed(const char *why) { if (!mal_) { mal_ = true; why_ = why; } }
  void Unsupported(const char *why) { if (!mal_ && !uns_) { uns_ = true; why_ = why; } }
  Outcome outcome() const { return mal_ ? kMalformed : uns_ ? kUnsupported : kOk; }
  const std::string &why() const { return why_; }
  bool malformed() const { return mal_; }
  bool unsupported() const { return uns_; }
private:
  bool mal_ = false, uns_ = false;
  std::string why_;
};

// 3.1 str8 content: valid UTF-8, no C0 control characters.
inline bool ValidText(const std::string &s) {
  const unsigned char *p = (const unsigned char *)s.data();
  size_t n = s.size(), i = 0;
  while (i < n) {
    unsigned char c = p[i];
    if (c < 0x20) return false;
    if (c < 0x80) { i++; continue; }
    int len;
    uint32_t cp;
    if ((c & 0xE0) == 0xC0) { len = 2; cp = c & 0x1F; }
    else if ((c & 0xF0) == 0xE0) { len = 3; cp = c & 0x0F; }
    else if ((c & 0xF8) == 0xF0) { len = 4; cp = c & 0x07; }
    else return false;
    if (i + (size_t)len > n) return false;
    for (int k = 1; k < len; k++) {
      if ((p[i + k] & 0xC0) != 0x80) return false;
      cp = (cp << 6) | (p[i + k] & 0x3F);
    }
    // Overlong forms, surrogates and past U+10FFFF are not UTF-8.
    if ((len == 2 && cp < 0x80) || (len == 3 && cp < 0x800) || (len == 4 && cp < 0x10000) ||
        (cp >= 0xD800 && cp <= 0xDFFF) || cp > 0x10FFFF)
      return false;
    i += (size_t)len;
  }
  return true;
}

// ---- 3.1 TIME and TLV --------------------------------------------------------

struct Time {
  double jd1 = 0.0, jd2 = 0.0;
  bool IsZero() const { return jd1 == 0.0 && jd2 == 0.0; }
  double Sum() const { return jd1 + jd2; }
};
inline bool operator==(const Time &a, const Time &b) { return a.jd1 == b.jd1 && a.jd2 == b.jd2; }

inline Time ReadTime(Reader &r, Verdict &v) {
  Time t;
  t.jd1 = r.f64();
  t.jd2 = r.f64();
  if (!std::isfinite(t.jd1) || !std::isfinite(t.jd2) ||
      std::fabs(t.jd1) + std::fabs(t.jd2) > kJdAbsMax)
    v.Malformed("TIME not finite or outside |jd| <= 1e8");
  return t;
}
inline void WriteTime(Writer &w, const Time &t) { w.f64(t.jd1); w.f64(t.jd2); }

inline std::string ReadText(Reader &r, Verdict &v, const char *what) {
  std::string s = r.str8();
  if (r.ok() && !ValidText(s)) v.Malformed(what);
  return s;
}

struct Tlv {
  uint16_t tag = 0;
  std::string value;   // the payload bytes
};
using TlvList = std::vector<Tlv>;

// knownTags: the tags this message type assigns (NULL-free array). An
// unknown critical tag is unsupported; an unknown non-critical tag is kept
// and flagged via *pfIgnored.
inline TlvList ReadTlv(Reader &r, Verdict &v, const uint16_t *known, size_t cKnown,
                       bool *pfIgnored = nullptr) {
  TlvList out;
  uint16_t total = r.u16();
  const uint8_t *area = r.bytes(total);
  if (!r.ok()) return out;
  Reader t(area, total);
  int prev = -1;
  while (t.left() > 0) {
    Tlv e;
    e.tag = t.u16();
    uint16_t len = t.u16();
    const uint8_t *p = t.bytes(len);
    if (!t.ok()) { v.Malformed("TLV entry runs past its area"); return out; }
    if ((int)e.tag <= prev) v.Malformed("TLV tags not strictly ascending");
    prev = e.tag;
    e.value.assign((const char *)p, len);
    bool fKnown = false;
    for (size_t i = 0; i < cKnown; i++)
      if (known[i] == e.tag) fKnown = true;
    if (!fKnown) {
      if (e.tag & kTagCritical) v.Unsupported("unknown critical extension");
      else if (pfIgnored) *pfIgnored = true;
    }
    out.push_back(std::move(e));
  }
  return out;
}
inline void WriteTlv(Writer &w, const TlvList &list) {
  size_t at = w.size();
  w.u16(0);
  size_t start = w.size();
  for (const Tlv &e : list) {
    w.u16(e.tag);
    w.u16((uint16_t)e.value.size());
    w.raw(e.value.data(), e.value.size());
  }
  w.patchU16(at, (uint16_t)(w.size() - start));
}
// A TLV payload that is exactly one str8 (the REQUEST pins, a precession model).
inline bool TlvStr8(const Tlv &e, std::string *out) {
  if (e.value.empty() || (uint8_t)e.value[0] + 1u != e.value.size()) return false;
  *out = e.value.substr(1);
  return ValidText(*out);
}

// ---- 3.2 envelope ----------------------------------------------------------------

struct Envelope {
  uint8_t version = kProtoVersion;
  uint8_t flags = 0;
  uint16_t type = 0;
  uint32_t requestId = 0;
  uint32_t payloadLen = 0;
};

inline void WriteEnvelope(std::vector<uint8_t> *out, uint16_t type, uint32_t requestId,
                          size_t payloadLen, uint8_t version = kProtoVersion,
                          uint8_t flags = 0) {
  Writer w(out);
  w.u16(kMagic); w.u8(version); w.u8(flags); w.u16(type); w.u16(0);
  w.u32(requestId); w.u32((uint32_t)payloadLen);
}

// Structure only: magic, reserved, flag bits, and that the payload length
// matches the bytes present. Versions are the session's business (3.3):
// a version < 4 is an older client owed a legacy ERROR 8.
inline Outcome ParseEnvelope(const uint8_t *p, size_t n, Envelope *e, std::string *why) {
  if (n < kEnvelopeSize) { *why = "shorter than the envelope"; return kMalformed; }
  Reader r(p, kEnvelopeSize);
  if (r.u16() != kMagic) { *why = "bad magic"; return kMalformed; }
  e->version = r.u8();
  e->flags = r.u8();
  e->type = r.u16();
  uint16_t reserved = r.u16();
  e->requestId = r.u32();
  e->payloadLen = r.u32();
  if (reserved != 0) { *why = "envelope reserved field nonzero"; return kMalformed; }
  if (e->version >= kProtoMin && (e->flags & ~kEnvFlagZstd)) {
    *why = "unknown envelope flag bits";
    return kMalformed;
  }
  if ((size_t)e->payloadLen != n - kEnvelopeSize) {
    *why = "payload length does not match the frame";
    return kMalformed;
  }
  return kOk;
}

// 3.2: which messages carry a request id, which carry 0, which either.
inline Outcome CheckRequestId(const Envelope &e, std::string *why) {
  switch (e.type) {
    case kMsgHello: case kMsgWelcome:
      if (e.requestId != 0) { *why = "HELLO/WELCOME with a nonzero requestId"; return kMalformed; }
      break;
    case kMsgRequest: case kMsgData: case kMsgCancel: case kMsgLookup:
    case kMsgLookupResult: case kMsgSegData:
      if (e.requestId == 0) { *why = "requestId 0 on a request-scoped message"; return kMalformed; }
      break;
    default: break;
  }
  return kOk;
}

// ---- 3.4 HELLO ------------------------------------------------------------------------

struct Hello {
  uint32_t protoMax = kProtoVersion, protoMin = kProtoMin, build = 0, caps = 0;
  std::string clientName, token;
  TlvList ext;
};

inline Outcome ParseHello(const uint8_t *p, size_t n, Hello *h, std::string *why) {
  Reader r(p, n);
  Verdict v;
  h->protoMax = r.u32();
  h->protoMin = r.u32();
  h->build = r.u32();
  h->caps = r.u32();
  h->clientName = ReadText(r, v, "clientName is not text");
  h->token = ReadText(r, v, "token is not text");
  h->ext = ReadTlv(r, v, nullptr, 0);
  if (!r.ok()) v.Malformed("HELLO truncated");
  else if (r.left()) v.Malformed("bytes after HELLO");
  if (h->protoMin < kProtoMin || h->protoMin > h->protoMax)
    v.Malformed("protoMin must be >= 4 and <= protoMax");
  if (h->token.size() > kTokenMax) v.Malformed("token longer than 128 bytes");
  *why = v.why();
  return v.outcome();
}
inline void EncodeHello(std::vector<uint8_t> *pay, const Hello &h) {
  Writer w(pay);
  w.u32(h.protoMax); w.u32(h.protoMin); w.u32(h.build); w.u32(h.caps);
  w.str8(h.clientName); w.str8(h.token); WriteTlv(w, h.ext);
}

