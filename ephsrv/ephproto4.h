// Ephemeris protocol version 4: the byte-level codec.
//
// EPHEMERIS_PLUGINS_PLAN.md section 3 is the specification this implements;
// every rule below cites its subsection. Version 4 is source-neutral --
// bodies are NAIF/SPK-IDs with typed extras, options are explicit fields in
// per-object profiles, instants are two-part Julian dates -- so any engine
// can serve it without a map from Swiss Ephemeris numbering (the reason for
// the break from version 3, ephproto.h).
//
// Compiled into both ends, header-only, no dependencies beyond the standard
// library. Everything moves through the explicit little-endian Writer and
// Reader; nothing is ever cast onto wire bytes. Parsers are canonical: they
// REFUSE input a conforming encoder could not have produced (3.1), because
// the result cache keys on the question block's bytes (3.7) and two
// spellings of one question would be two cache entries and two answers.
//
// Outcomes: kOk; kMalformed (the peer broke a rule: ERROR 1); kUnsupported
// (a registry value or critical extension this end does not implement:
// ERROR 11 -- registries grow, so an unknown value is not a broken peer).
// Where both apply, malformed wins.
//
// ephsrv/conformance/ holds the fixtures that pin this codec to the
// specification, generated by tools/ephproto4-fixtures.py from the spec
// text alone; ephsrv/ephproto4_test.cpp runs them.

